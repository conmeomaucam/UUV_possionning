clear all; clc;
fprintf('>>> Dang khoi tao cau hinh Coder dung Struct...\n');

cfg = coder.config('lib');
cfg.TargetLang = 'C';
cfg.TargetLangStandard = 'C99 (ISO)';
cfg.GenCodeOnly = true;
cfg.GenerateReport = true;
cfg.EnableMemcpy = true;

% Dung gia tri logical/boolean hop le theo dung thong bao loi cua MATLAB:
cfg.EnableDynamicMemoryAllocation = false;

cfg.HardwareImplementation.ProdHWDeviceType = 'Texas Instruments->C2000';

%% Dinh nghia mau Struct cho Coder
sample_init = struct( ...
    'initial_rpy',    zeros(3, 1), ...
    'gravity',        double(9.80665), ...
    'acc_vrw',        double(0), ...
    'gyro_arw',       double(0), ...
    'acc_bias_sigma', double(0), ...
    'acc_bias_tau',   double(3600), ...
    'gyro_bias_rw',   double(0), ...
    'scale_rw',       double(0), ...
    'boresight_rw',   double(0), ...
    'dt',             double(0.01));

sample_meas = struct( ...
    'gyro',        zeros(3, 1), ...
    'accel',       zeros(3, 1), ...
    'gnss',        zeros(7, 1), ...
    'depth',       double(0), ...
    'dvl',         zeros(3, 1), ...
    'gnss_valid',  false, ...
    'depth_valid', false, ...
    'dvl_valid',   false);

sample_cfg = struct( ...
    'dt',              double(0.01), ...
    'gravity',         double(9.80665), ...
    'w_ie_ned',        zeros(3, 1), ...
    'radius_n',        double(6378137.0), ...
    'radius_m',        double(6356752.0), ...
    'tan_latitude',    double(0), ...
    'height',          double(0), ...
    'lever_arm_body',  zeros(3, 1), ...
    'dvl_noise_floor', double(0.01), ...
    'dvl_noise_slope', double(0.005), ...
    'gps_pos_sigma',   double(1.5), ...
    'gps_vel_sigma',   double(0.1), ...
    'gps_yaw_sigma',   double(0.02), ...
    'depth_sigma',     double(0.1));

t_mode = coder.typeof(double(0));
t_init = coder.typeof(sample_init);
t_meas = coder.typeof(sample_meas);
t_cfg  = coder.typeof(sample_cfg);

codegen -config cfg -o esekf19_c2000 esekf19_app -args {t_mode, t_init, t_meas, t_cfg}
fprintf('>>> Da sinh ma xong vao codegen/lib/esekf19_c2000/!\n');