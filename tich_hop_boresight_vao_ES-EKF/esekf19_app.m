%#codegen
function [state_out, status, nis] = esekf19_app(mode, init_in, meas_in, cfg_in)
% ESEKF19_APP Giao dien Wrapper cap cao duoc dong goi bang Struct.
% - mode: 0 = Khoi tao (Init), 1 = Chay buoc loc (Step)
% - state_out: Struct chua vi tri, van toc, quaternion, bias, boresight ro rang

% Khai bao bo nho tinh (static) luu tru trang thai bo loc giua cac chu ky
persistent x P Q cfg_raw
if isempty(x)
    x = zeros(20, 1);
    P = zeros(19, 19);
    Q = zeros(19, 19);
    cfg_raw = zeros(18, 1);
end

status = zeros(3, 1);
nis    = zeros(3, 1);

%% 1. CHE DO KHOI TAO (MODE = 0)
if mode == 0
    noise_cfg_raw = [ ...
        init_in.acc_vrw; ...
        init_in.gyro_arw; ...
        init_in.acc_bias_sigma; ...
        init_in.acc_bias_tau; ...
        init_in.gyro_bias_rw; ...
        init_in.scale_rw; ...
        init_in.boresight_rw; ...
        init_in.dt];

    % Goi truc tiep ham esekf19_init goc
    [x, P, Q] = esekf19_init(init_in.initial_rpy, init_in.gravity, noise_cfg_raw);

    % Luu mang cfg phẳng cho cac chu ky step ve sau
    cfg_raw = [ ...
        cfg_in.dt; ...
        cfg_in.gravity; ...
        cfg_in.w_ie_ned; ...
        cfg_in.radius_n; ...
        cfg_in.radius_m; ...
        cfg_in.tan_latitude; ...
        cfg_in.height; ...
        cfg_in.lever_arm_body; ...
        cfg_in.dvl_noise_floor; ...
        cfg_in.dvl_noise_slope; ...
        cfg_in.gps_pos_sigma; ...
        cfg_in.gps_vel_sigma; ...
        cfg_in.gps_yaw_sigma; ...
        cfg_in.depth_sigma];

    %% 2. CHE DO CHAY BUOC LOC (MODE = 1)
else
    flags_raw = [double(meas_in.gnss_valid); ...
        double(meas_in.depth_valid); ...
        double(meas_in.dvl_valid)];

    % Goi truc tiep ham esekf19_step goc
    [x, P, status, nis] = esekf19_step( ...
        x, P, Q, ...
        meas_in.gyro, meas_in.accel, ...
        meas_in.gnss, meas_in.depth, meas_in.dvl, ...
        flags_raw, cfg_raw);
end

%% 3. DONG GOI KET QUA RA STRUCT MINH BACH
state_out = struct( ...
    'pos_ned',        x(1:3), ...
    'vel_ned',        x(4:6), ...
    'quaternion',     x(7:10), ...
    'accel_bias',     x(11:13), ...
    'gyro_bias',      x(14:16), ...
    'dvl_scale',      x(17), ...
    'dvl_boresight',  x(18:20));
end